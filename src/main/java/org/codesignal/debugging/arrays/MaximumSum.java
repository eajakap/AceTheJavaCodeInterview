package org.codesignal.debugging.arrays;

/**
 * You are given an array of n integers, where n ranges from $1$ to $10^5$, inclusive, and each number falls within
 * the range of $-10^5$ to $10^5$, inclusive. Your task is to find the subarray (continuous section) of
 * length k ($1 \le k \le n$) that has the maximum sum using the two-pointer technique.
 *
 * The function, maximum_sum, should take an array numbers and an integer k as inputs, and return a pair containing
 * two integers: the largest sum of a k-length subarray and the index of the first element of this subarray.
 * If more than one subarray yields the same maximum sum, return the one with the lowest starting index.
 *
 * The time complexity of your solution should be linear, i.e., O(n), where n is the number of elements in the numbers array.
 *
 * Expect an input in the following manner:
 *
 * Java
 * Copy to clipboard
 * app.maximumSum(new int[]{2, 1, 5, 1, 3, 2}, 3);
 * In this example, when k = 3, the subarrays are {2, 1, 5}, {1, 5, 1}, {5, 1, 3}, and {1, 3, 2}.
 * The maximum sum among these is 9, generated by the subarray {5, 1, 3}.
 * Therefore, the function's output should be a pair: (9, 2).
 * The first number represents the maximum sum, and the second number indicates the index of the first element of the maximum subarray.
 *
 * For the same array, if k = 2,
 *
 * Java
 * Copy to clipboard
 * app.maximumSum(new int[]{2, 1, 5, 1, 3, 2}, 2);
 * The subarrays are {2, 1}, {1, 5}, {5, 1}, {1, 3}, and {3, 2}. The maximum sum among these is 6,
 * which is generated by the subarray {1, 5}. The output in this case should be (6, 1).
 *
 * Hint: For solving this task, you should use the two pointers technique, where both pointers move to the right.
 */
public class MaximumSum {

    public int[] maximumSum(int[] numbers, int k) {
        // TODO: Implement the function to find maximum subarray of size k in numbers
        int left = 0;
        long maximum_sum = Long.MIN_VALUE;
        long current_sum = 0;
        if (numbers == null || numbers.length == 0) return new int[]{0, 0};
        // Use sliding window approach
        for (int right = 0; right < numbers.length; right++) {
            // Add the rightmost element to the sum
            current_sum += numbers[right];
            // If the sum becomes greater than the current maximum, update the maximum sum and the left index
            if (right >= k - 1) { // fixed sliding window size (k==> 0 - k-1)
                if (current_sum > maximum_sum) {
                    maximum_sum = current_sum;
                    left = right - k + 1;
                }
                // Remove the leftmost element from the sum
                current_sum -= numbers[right - k + 1];
                // expanded window
            }
        }

        return new int[]{(int)maximum_sum, left};
    }

    public static void main(String[] args) {
        MaximumSum app = new MaximumSum();
        int[] numbers = {2, 1, 5, 1, 3, 2};
        int k = 3;
        int[] result = app.maximumSum(numbers, k);
        System.out.println(result[0] + " " + result[1]);
    }
}
